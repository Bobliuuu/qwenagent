"""results/*.json -> results/TABLE.md, and injects the headline block into README.md between markers."""
import os, sys, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *

def fmt(s): return "n/a" if s is None else f"{100*s[0]:.1f} ± {100*s[1]:.1f}"

def table_for(pre, res):
    a = info(res); Ps = sorted({p for m in res for p in pkeys(res[m])}); trP = a["train_P"]
    L = [f"**{pre}**: task `{a['task']}`, trained on P in {{{trP}}}, {a['steps']} steps, K={a['K']}, layer {a['layer']}; "
         f"accuracy in %, mean ± std (population std) over n seeds; chance = 10%.", ""]
    L.append("| mode | n seeds | trainable params | " + " | ".join(f"P={p}" for p in Ps) + " |")
    L.append("|---|---|---|" + "---|" * len(Ps))
    for m in MODES:
        if m not in res: continue
        runs = res[m]; pr = runs[0].get("params")
        L.append(f"| {m} | {len(runs)} | {f'{pr:,}' if pr else 'not recorded'} | " + " | ".join(fmt(stat(runs, f'P{p}')) for p in Ps) + " |")
    ab = [m for m in MODES if m in res and abl_prefix(res[m])]
    if ab:
        p0 = abl_prefix(res[ab[0]]).rstrip("_")
        L += ["", f"Intervention ablations at {p0} (accuracy %, mean ± std):", "",
              "| mode | intact | zero return | shuffle across batch | drop slot 0 |", "|---|---|---|---|---|"]
        for m in ab:
            p = abl_prefix(res[m])
            L.append(f"| {m} | " + " | ".join(fmt(stat(res[m], k)) for k in (p.rstrip("_"), p + "zero", p + "shuffle", p + "drop:0")) + " |")
    return "\n".join(L)

def facts(data):
    """auto-generated factual bullets; every number comes from results/*.json"""
    L = []
    for pre in sorted(data, reverse=True):
        res = data[pre]; Ps = sorted({p for m in res for p in pkeys(res[m])}); P = Ps[-1]
        L.append(f"- `{pre}`, P={P} (largest test size): " + "; ".join(
            f"{m} {fmt(stat(res[m], f'P{P}'))} (per seed: " + ", ".join(f"{100*r['final'][f'P{P}']:.0f}" for r in sorted(res[m], key=lambda r: r['_seed'])) + ")"
            for m in MODES if m in res) + ".")
        for m in MODES:
            if m in res and abl_prefix(res[m]):
                p = abl_prefix(res[m]); z = stat(res[m], p + "zero")
                L.append(f"  - `{m}` with the return zeroed at {p.rstrip('_')}: {fmt(z)} (intact {fmt(stat(res[m], p.rstrip('_')))}).")
    return "\n".join(L)

def hero():
    import glob
    g = sorted(glob.glob(os.path.join(ROOT, "figures", "gif_q3_multi_s0_P*.gif")))
    if g: return "\n".join(f"![router assignment streaming over a program]({os.path.relpath(x, ROOT)})" for x in g[-1:])
    return "_Hero animation lands as soon as the q3 traces are pulled into `traces/` and `viz/build_all.sh` is re-run._"

def inject(r, tag, body):
    return re.sub(rf"<!-- {tag}:BEGIN.*?<!-- {tag}:END -->", lambda m: f"<!-- {tag}:BEGIN (generated) -->\n{body}\n<!-- {tag}:END -->", r, flags=re.S)

def main():
    data = load(); blocks = []
    for pre in sorted(data, reverse=True): blocks.append(table_for(pre, data[pre]))
    headline = sorted(data)[-1] if data else None
    note = ""
    if headline:
        note = (f"Headline source: `{headline}` (the most recent experiment with results in `results/`). "
                + ("" if headline.startswith("q3") else "q3 results are not in the repo yet, so these are the older q2 numbers (task `query`, easier), clearly not the final claim. "))
    txt = "\n\n".join(blocks) + "\n"
    open(os.path.join(ROOT, "results", "TABLE.md"), "w").write("# Results tables (generated by viz/make_tables.py)\n\n" + note + "\n\n" + txt)
    rp = os.path.join(ROOT, "README.md"); r = open(rp).read()
    new = "<!-- RESULTS:BEGIN (generated by viz/make_tables.py, do not edit) -->\n" + note + "\n\n" + txt + "<!-- RESULTS:END -->"
    if "<!-- RESULTS:BEGIN" in r:
        r = re.sub(r"<!-- RESULTS:BEGIN.*?<!-- RESULTS:END -->", lambda m: new, r, flags=re.S)
        r = inject(r, "FACTS", facts(data)); r = inject(r, "HERO", hero()); open(rp, "w").write(r)
    print("tables written; headline", headline)
if __name__ == "__main__": main()
